import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { circleFixture } from '../fixtures';
const endpoint = '**/overpass-api.de/api/interpreter';
test('responsive map and synthetic-fixture routing/export flow', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  let requests = 0;
  await page.route(endpoint, async route => { requests++; await route.fulfill({ json: circleFixture(64, 850).data, headers: { 'access-control-allow-origin': '*' } }); });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Find your way around.' })).toBeVisible();
  await expect(page.locator('.leaflet-container')).toBeVisible();
  expect(requests).toBe(0);
  await expect(page.getByRole('button', { name: 'Export GPX' })).toHaveCount(0);
  await page.getByRole('button', { name: '5 km', exact: true }).click();
  await page.getByRole('button', { name: 'Find my circle' }).click();
  await expect(page.getByText('Loop found. Take a closer look, then take it outside.')).toBeVisible();
  expect(requests).toBe(1);
  await expect(page.locator('.metrics')).toContainText('5.34');
  await expect(page.getByRole('button', { name: 'Ideal circle' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Ideal circle' }).click();
  await expect(page.getByRole('button', { name: 'Ideal circle' })).toHaveAttribute('aria-pressed', 'false');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export GPX' }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/^great-circle-5.3km.gpx$/);
  const text = await readFile((await download.path())!, 'utf8');
  const validation = await page.evaluate(gpx => {
    const xml = new DOMParser().parseFromString(gpx, 'application/xml');
    const points = [...xml.getElementsByTagName('trkpt')];
    return { errors: xml.getElementsByTagName('parsererror').length, count: points.length, closed: points[0].outerHTML === points.at(-1)!.outerHTML, namespace: xml.documentElement.namespaceURI };
  }, text);
  expect(validation).toEqual({ errors: 0, count: 65, closed: true, namespace: 'http://www.topografix.com/GPX/1/1' });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(overflow).toBe(false);
  await page.screenshot({ path: `/tmp/great-circle-${info.project.name}-fixture.png`, fullPage: true });
  await page.getByRole('button', { name: '10 km', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Export GPX' })).toHaveCount(0);
  // Same-area preference changes reuse downloaded data, rather than hit Overpass.
  await page.getByRole('button', { name: '5 km', exact: true }).click();
  await page.getByRole('button', { name: 'Find my circle' }).click();
  await expect(page.getByText('Loop found. Take a closer look, then take it outside.')).toBeVisible();
  expect(requests).toBe(1);
  expect(errors).toEqual([]);
});
test('honest HTTP failure and cancellation, without stale export', async ({ page }) => {
  await page.route(endpoint, route => route.fulfill({ status: 429, body: 'Too many requests' }));
  await page.goto('/');
  await page.getByRole('button', { name: 'Find my circle' }).click();
  await expect(page.getByRole('alert')).toContainText('rate-limited');
  await expect(page.getByRole('button', { name: 'Export GPX' })).toHaveCount(0);
  await page.reload();
  await page.unroute(endpoint);
  await page.route(endpoint, async route => { await new Promise(resolve => setTimeout(resolve, 1200)); await route.fulfill({ json: circleFixture().data }).catch(() => {}); });
  await page.getByRole('button', { name: 'Find my circle' }).click();
  await page.getByRole('button', { name: 'Cancel search' }).click();
  await expect(page.getByRole('status', { name: 'Route status' })).toContainText('Cancelled.');
  await page.waitForTimeout(1500);
  await expect(page.getByRole('status', { name: 'Route status' })).toContainText('Cancelled.');
  await expect(page.getByRole('button', { name: 'Find my circle' })).toBeEnabled();
  await expect(page.getByRole('button', { name: 'Export GPX' })).toHaveCount(0);
});
test('coordinate controls validate input and reject an out-of-area start', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Start', exact: true }).click();
  await page.getByText('Use coordinates').click();
  await page.getByRole('textbox', { name: 'Latitude' }).fill('91');
  await page.getByRole('button', { name: 'Apply coordinates' }).click();
  await expect(page.getByRole('alert')).toContainText('latitude');
  await page.getByRole('textbox', { name: 'Latitude' }).fill('50');
  await page.getByRole('button', { name: 'Apply coordinates' }).click();
  await page.getByRole('button', { name: 'Find my circle' }).click();
  await expect(page.getByRole('alert')).toContainText('outside the search area');
});
